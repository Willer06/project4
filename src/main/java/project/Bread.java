package project;

/**
 * Represents the available types of bread for burgers and sandwiches.
 *
 * @author Benjamin Gluzman, William Becerra
 */
public enum Bread {
    /** Represents the brioche option. */
    BRIOCHE,

    /** Represents the wheat bread option. */
    WHEAT_BREAD,

    /** Represents the pretzel option. */
    PRETZEL,

    /** Represents the bagel option. */
    BAGEL,

    /** Represents the sourdough option. */
    SOURDOUGH;
}
