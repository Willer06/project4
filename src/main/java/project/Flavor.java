package project;

/**
 * Represents the fifteen beverage flavors offered by RU Burger.
 *
 * @author Benjamin Gluzman, William Becerra
 */
public enum Flavor {
    /** Represents the cola option. */
    COLA,

    /** Represents the lime option. */
    LIME,

    /** Represents the orange option. */
    ORANGE,

    /** Represents the cherry option. */
    CHERRY,

    /** Represents the tea option. */
    TEA,

    /** Represents the mango option. */
    MANGO,

    /** Represents the strawberry option. */
    STRAWBERRY,

    /** Represents the raspberry option. */
    RASPBERRY,

    /** Represents the grape option. */
    GRAPE,

    /** Represents the juice option. */
    JUICE,

    /** Represents the lemonade option. */
    LEMONADE,

    /** Represents the root beer option. */
    ROOT_BEER,

    /** Represents the peach option. */
    PEACH,

    /** Represents the pineapple option. */
    PINEAPPLE,

    /** Represents the watermelon option. */
    WATERMELON;

}
